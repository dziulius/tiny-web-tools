import {readFile, writeFile} from 'node:fs/promises';
import {buildMusic} from './music.mjs';

const sourceFiles = [
  'engine.js',
  'storage.js',
  'audio.js',
  'renderer.js',
  'input.js',
  'app.js'
];

const moduleImport = /import\s+(?:\{[\s\S]*?\}|[^;]+)\s+from\s+['"][^'"]+['"];\s*/g;
const moduleExport = /\bexport\s+(?=(?:const|function|class)\b)/g;

const sources = await Promise.all(
  sourceFiles.map(fileName => readFile(fileName, 'utf8'))
);

const bundledSource = sources
  .map(removeModuleSyntax)
  .join('\n\n');

const banner = '// Generated by build.mjs. Edit the source modules, not this file.\n';
const bundle = `${banner}(() => {\n${indent(bundledSource)}\n})();\n`;

await writeFile('game.js', bundle);
await buildMusic('music.wav');
console.log(`Built game.js and music.wav from ${sourceFiles.length} source modules.`);

function removeModuleSyntax(source) {
  return source
    .replace(moduleImport, '')
    .replace(moduleExport, '');
}

function indent(source) {
  return source
    .split('\n')
    .map(line => line ? `  ${line}` : '')
    .join('\n');
}
